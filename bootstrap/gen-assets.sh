#!/usr/bin/env bash
# Embeds the brand images (assets/) in src/bxrig/AssetData.bx as base64 (a generated class), like the catalog.
#   gen-assets.sh           rewrite src/bxrig/AssetData.bx
#   gen-assets.sh --check   fail if the generated class is out of date (CI)
# Rendering the images is separate: python3 assets/build.py && node assets/render.js
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bxrig/AssetData.bx"
files=(logo.png icons/16.png icons/24.png icons/32.png icons/48.png icons/64.png icons/128.png icons/256.png icons/bxrig.svg)
# The wallpapers (assets/wallpapers/<theme>.jpg, ~6 MB) are NOT embedded: compiling them in as base64 needs over 13 GB of memory.
# They travel in the signed install bundle and next to each release; the binary carries only their SHA-256 (WallpaperData) to check them.
wout="$root/src/bxrig/WallpaperData.bx"
{
  echo '// GENERATED by bootstrap/gen-assets.sh from assets/wallpapers/. Do not edit by hand.'
  echo '// One wallpaper per bundled theme; the files are not embedded, only their SHA-256 (bxrig.Wallpapers finds or downloads them and checks them).'
  echo 'class WallpaperData {'
  printf '    function names() { return [ '; sep=''; for w in "$root"/assets/wallpapers/*.jpg; do printf '%s"%s"' "$sep" "$(basename "$w" .jpg)"; sep=', '; done; echo ' ]; }'
  echo '    function sha256( name ) {'
  echo '        switch ( arguments.name ) {'
  for w in "$root"/assets/wallpapers/*.jpg; do echo "            case \"$(basename "$w" .jpg)\": return \"$(sha256sum "$w" | awk '{print $1}')\";"; done
  echo '        }'
  echo '        return "";'
  echo '    }'
  echo '}'
} > "$wout.new"
{
  echo '// GENERATED by bootstrap/gen-assets.sh from assets/. Do not edit by hand.'
  echo 'class AssetData {'
  echo '    function names() {'
  printf '        return [ '; sep=''; for f in "${files[@]}"; do printf '%s"%s"' "$sep" "$f"; sep=', '; done; echo ' ];'
  echo '    }'
  echo '    function base64( name ) {'
  echo '        switch ( arguments.name ) {'
  for f in "${files[@]}"; do
    echo "            case \"$f\":"
    echo "                return '$(base64 -w0 "$root/assets/$f")';"
  done
  echo '        }'
  echo '        return "";'
  echo '    }'
  echo '}'
} > "$out.new"
if [[ "${1:-}" == --check ]]; then
  cmp -s "$wout.new" "$wout" || { rm -f "$wout.new" "$out.new"; echo 'src/bxrig/WallpaperData.bx is out of date: run bootstrap/gen-assets.sh' >&2; exit 1; }
  rm -f "$wout.new"
  cmp -s "$out.new" "$out" && { rm -f "$out.new"; echo 'asset embed is current'; } || { rm -f "$out.new"; echo 'src/bxrig/AssetData.bx is out of date: run bootstrap/gen-assets.sh' >&2; exit 1; }
else
  mv "$wout.new" "$wout"
  mv "$out.new" "$out"; echo "embedded ${#files[@]} images into src/bxrig/AssetData.bx ($(wc -c < "$out") bytes)"
fi
