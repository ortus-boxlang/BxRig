#!/usr/bin/env bash
# Writes src/bxrig/WallpaperData.bx (a generated class): the theme wallpapers' names and SHA-256.
# The wallpapers (assets/wallpapers/<theme>.jpg, ~6 MB) are not packed into the binary: they travel in the signed install bundle
# and next to each release, and bxrig.Wallpapers checks them against these hashes. The brand images are resources (src/resources/assets).
# It also writes src/bxrig/IconThemeData.bx: the files of the BxRig icon theme (assets/icons/theme/BxRig, made by tools/gen-icon-theme.py), embedded as resources.
#   gen-assets.sh           rewrite src/bxrig/WallpaperData.bx and src/bxrig/IconThemeData.bx
#   gen-assets.sh --check   fail if one is out of date, or the icon theme files are (CI)
# Rendering the images is separate: python3 assets/build.py && node assets/render.js
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
wout="$root/src/bxrig/WallpaperData.bx"
{
	echo '// GENERATED by bootstrap/gen-assets.sh from assets/wallpapers/. Do not edit by hand.'
	echo '// One wallpaper per bundled theme; the files are not embedded, only their SHA-256 (bxrig.Wallpapers finds or downloads them and checks them).'
	echo 'class WallpaperData {'
	printf '    function names() { return [ '; sep=''; for w in "$root"/assets/wallpapers/*.jpg; do printf '%s"%s"' "$sep" "$(basename "$w" .jpg)"; sep=', '; done; echo ' ]; }'
	echo '    function sha256( name ) {'
	echo '        switch ( arguments.name ) {'
	for w in "$root"/assets/wallpapers/*.jpg; do echo "            case \"$(basename "$w" .jpg)\": return \"$(sha256sum "$w" | awk '{print $1}')\";"; done
	echo '        }'
	echo '        return "";'
	echo '    }'
	echo '}'
} | python3 "$root/tools/format.py" --stdin "$wout" > "$wout.new"   # tabs, like every file (tools/format.py)
if [[ "${1:-}" == --check ]]; then
	cmp -s "$wout.new" "$wout" && { rm -f "$wout.new"; echo 'wallpaper hashes are current'; } || { rm -f "$wout.new"; echo 'src/bxrig/WallpaperData.bx is out of date: run bootstrap/gen-assets.sh' >&2; exit 1; }
else
	mv "$wout.new" "$wout"; echo "wrote the hashes of $(ls "$root"/assets/wallpapers/*.jpg | wc -l) wallpapers into src/bxrig/WallpaperData.bx"
fi

# the icon theme: every file under assets/icons/theme/BxRig, as a resource name
iout="$root/src/bxrig/IconThemeData.bx"
{
	echo '// GENERATED by bootstrap/gen-assets.sh from assets/icons/theme/BxRig/. Do not edit by hand.'
	echo '// The files of the BxRig icon theme (index.theme, scalable SVGs, PNGs, licence), packed as resources; bxrig.IconThemeInstall writes them to ~/.local/share/icons/BxRig.'
	echo 'class IconThemeData {'
	echo '    function names() {'
	echo '        return ['
	(cd "$root/assets/icons/theme" && find BxRig -type f | LC_ALL=C sort) | awk 'BEGIN{n=0}{printf "%s            \"%s\"", (n++?",\n":""), $0}END{print ""}'
	echo '        ];'
	echo '    }'
	echo '    function binary( name ) { return new bxrig.util.Res().binary( "assets/icons/theme/" & arguments.name ); }'
	echo '}'
} | python3 "$root/tools/format.py" --stdin "$iout" > "$iout.new"
if [[ "${1:-}" == --check ]]; then
	python3 "$root/tools/gen-icon-theme.py" --check
	cmp -s "$iout.new" "$iout" && { rm -f "$iout.new"; echo 'icon theme list is current'; } || { rm -f "$iout.new"; echo 'src/bxrig/IconThemeData.bx is out of date: run bootstrap/gen-assets.sh' >&2; exit 1; }
else
	mv "$iout.new" "$iout"; echo "wrote the $(find "$root/assets/icons/theme/BxRig" -type f | wc -l) icon theme files into src/bxrig/IconThemeData.bx"
fi
