#!/usr/bin/env bash
# Writes src/bxrig/util/Version.bx (a generated class) from the version in box.json: the one source of the version string.
#   gen-version.sh           rewrite src/bxrig/util/Version.bx
#   gen-version.sh --check   fail if the generated class is out of date (CI)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bxrig/util/Version.bx"
version="$(sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p' "$root/box.json" | head -1)"
[[ -n "$version" ]] || { echo "no version in box.json" >&2; exit 1; }
{
  echo '// GENERATED by bootstrap/gen-version.sh from box.json. Do not edit by hand.'
  echo 'class Version {'
  echo "    function current() { return \"$version\"; }"
  echo '}'
} > "$out.tmp"
if [[ "${1:-}" == "--check" ]]; then
  cmp -s "$out.tmp" "$out" || { rm -f "$out.tmp"; echo "Version.bx is out of date: run bootstrap/gen-version.sh" >&2; exit 1; }
  rm -f "$out.tmp"
else mv "$out.tmp" "$out"; fi
